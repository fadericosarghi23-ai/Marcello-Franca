import type { Img } from '../lib/img';

/** id = slug dell'URL /progetti/<id>/ (minuscole e trattini) */
export type CategoriaId = string;

export type Categoria = {
  id: CategoriaId;
  /** Nome esteso (filtri, breadcrumb, scheda) */
  nome: string;
  /** Etichetta corta sulla card */
  etichetta: string;
  /** Testo introduttivo della pagina categoria */
  intro: string;
  /** Meta title della pagina categoria */
  metaTitle: string;
  metaDescription: string;
};

export type Progetto = {
  slug: string;
  titolo: string;
  luogo: string;
  /** Prima = categoria principale (breadcrumb, etichetta card) */
  categorie: CategoriaId[];
  /** Temi: la card ne mostra i primi 3, la scheda tutti */
  tag: string[];
  /** Foto di copertina (card + hero della pagina progetto); di solito = prima foto della galleria */
  copertina: Img;
  /** false = pagina senza foto grande in testa (es. progetti con soli disegni) */
  hero: boolean;
  /** true = la copertina è un disegno/render: la card la mostra intera su fondo chiaro */
  disegno?: boolean;
  intervento: string;
  progettisti?: string[];
  importo?: string;
  /** id del membro del team (src/data/team.ts) */
  referente: string;
  /** Descrizione in HTML semplice (<p>, <ul><li>) */
  testo: string;
  /** Galleria; la prima è la copertina. classe: '' | 'tall' (verticale) | 'wide' (panoramica), + ' drawing' per i disegni */
  galleria: { img: Img; classe: string }[];
  /** Slug di 3 progetti simili (se assente: stessa categoria) */
  simili?: string[];
};

